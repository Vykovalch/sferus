import { Plus } from "lucide-react";
import Link from "next/link";
import { PageContainer } from "@/components/shared/PageContainer";
import { SearchBar } from "@/components/shared/SearchBar";
import { getCities } from "@/features/cities/queries";

export async function HeroSection() {
  const cities = await getCities();

  return (
    // Фон — светлый холст шапки (`--hero-bg`) и нарисованный город понизу
    // (решение владельца, 2026-09-21). До этого здесь лежало стоковое фото
    // под белым слоем 85%: снимок был не местный, под слоем от него оставались
    // бледные силуэты, и первый экран читался как серое пятно.
    //
    // Иллюстрация — подложка под текстом, а не полоса под ним (решение
    // владельца, 2026-09-21): заголовок и поиск стоят на её небе с облаками.
    // 16% в нижнем отступе — не декоративное число: у холста 1440×398 линия
    // крыш дальнего ряда проходит на 227px от низа, это 16% ширины. Такой
    // отступ держит подпись над крышами на любой ширине, а сам рисунок
    // продолжает уходить под текст.
    //
    // Слагаемое 1rem компенсирует подъём подписи: отступ от поиска до неё
    // уменьшен с 40px до 24px (решение владельца, 2026-09-21), и без добавки
    // секция стала бы на 16px короче — вместе с подписью поднялись бы и дома.
    // Поднимается только строка, город стоит на месте.
    //
    // Отступ сверху равен отступу между заголовком и поиском — 48px
    // (`mb-12` у `h1`), решение владельца 2026-09-21. До этого было 64px
    // на телефоне и 128px от 768px: заголовок висел слишком низко от шапки.
    <section className="relative pt-12 pb-[calc(16%+1rem)] overflow-hidden bg-hero-bg">
      {/* Декоративная иллюстрация: девяти- и пятиэтажки, деревья, тротуар
          с бордюром, облака и солнце. Вектор, нарисован под этот сайт;
          в цветах палитры — холодные серые, фирменный жёлтый только
          в нескольких окнах и в солнце.
          Фоном, а не `<img>`: картинка ничего не сообщает, в разметке ей делать
          нечего. `next/image` тоже не нужен — SVG не растрируют и не режут
          на размеры, оптимизатору с ним делать нечего. */}
      <div
        aria-hidden="true"
        className="pointer-events-none absolute inset-x-0 bottom-0 aspect-[1440/398] bg-bottom bg-no-repeat bg-[length:100%_auto]"
        // Адрес — инлайн-стилем, а не классом с `url()` в имени: Turbopack
        // разрешает `url()` внутри CSS как модуль и на сборке падает
        // «Module not found» (2026-09-21). Из стиля он путь не трогает —
        // файл отдаётся из `public/`, как и прежнее фото первого экрана.
        style={{ backgroundImage: "url('/hero-city.svg')" }}
      />

      <PageContainer className="relative z-10">
        <div className="max-w-4xl mx-auto text-center">
          <h1 className="text-3xl sm:text-4xl md:text-5xl font-semibold tracking-wide mb-12 leading-[1.15] text-balance">
            Найди услугу
            <br className="hidden sm:inline" />
            {/* Весь заголовок одним цветом текста: цвет бренда на первом экране —
                только у кнопки «Найти», целевого действия. Пробел нужен на
                мобильном, где перенос скрыт. */}
            {" в Приднестровье"}
          </h1>

          {/* 24px до строки «Нужен исполнитель…» вместо прежних 40px (решение
              владельца, 2026-09-21): подпись относится к поиску и должна
              читаться вместе с ним, а не как отдельный блок. */}
          <div className="mb-6 max-w-3xl mx-auto">
            <SearchBar cities={cities} trackVisibility />
          </div>

          {/* Счётчики «400+ исполнителей / 500+ объявлений / 50+ активных заданий»
              удалены: цифры были вписаны руками и не сходились с базой на два
              порядка. Для площадки услуг это не украшение вёрстки, а заявление
              о размере рынка, и оно должно быть правдой.

              Реальные значения сюда не подставлены сознательно: на старте они
              честные, но выглядят хуже, чем их отсутствие. Вернуть счётчики
              имеет смысл тогда, когда цифра начнёт работать на площадку —
              и уже запросом к БД, а не константой в разметке. */}
          <div className="flex flex-col sm:flex-row items-center justify-center gap-3 text-base">
            <span className="text-muted-foreground font-medium">
              Нужен исполнитель под конкретную задачу?
            </span>
            {/* Контурная кнопка, а не ссылка (решение владельца, 2026-09-21):
                текстовая ссылка с подчёркиванием не читалась как действие,
                создающее объявление. Оформление — как у «Разместить» в шапке:
                жёлтая рамка, тёмный текст, знак «+»; всё, что создаёт
                объявление, выглядит на сайте одинаково.

                Заливки нет: на первом экране она закреплена за «Найти»
                (DESIGN.md), две заливки рядом спорили бы. Заливается только
                при наведении, как в шапке. Рамка на светлом фоне даёт 1.5:1 —
                кнопку опознают по тексту (17:1), не по рамке.

                Высота 44px вместо прежних 40px в шапке: здесь кнопка видна
                и на телефоне, а 44px — минимальная зона касания. Поэтому
                `tap-target` ей больше не нужен.

                До 2026-09-21 здесь была ссылка: тёмный текст с золотым
                подчёркиванием (решение владельца 2026-09-20, принятое под
                фотографию первого экрана — золотой текст на ней падал
                до 3.46:1). */}
            <Link
              href="/tasks/new"
              className="inline-flex h-11 items-center gap-2 rounded-full border border-brand-fill px-5 font-semibold text-foreground transition-colors hover:bg-brand-fill hover:text-brand-fill-foreground"
            >
              <Plus aria-hidden="true" className="size-4" />
              Создать задание
            </Link>
          </div>
        </div>
      </PageContainer>
    </section>
  );
}
