/**
 * Правило суточной квоты на раскрытие контактов.
 *
 * Вынесено из `actions.ts` отдельным модулем по двум причинам. Первая —
 * логика общая для трёх действий раскрытия (порог из ARCHITECTURE.md,
 * раздел 4). Вторая важнее: из файла с `'use server'` нельзя экспортировать
 * ничего, кроме серверных действий, поэтому иначе это правило вообще нечем
 * было бы покрыть тестами — а оно защищает единственный канал связи в v1.
 *
 * Модуль намеренно без обращений к базе и без `server-only`: чистые функции,
 * которые получают уже посчитанные числа.
 */

/**
 * Сколько **разных** контактов пользователь может открыть за сутки.
 *
 * Тридцать — щедро для человека (за день редко открывают больше десятка)
 * и медленно для сборщика базы: три сотни объявлений он будет вычерпывать
 * больше недели, оставляя след в журнале раскрытий.
 */
export const REVEAL_LIMIT_PER_DAY = 30;

/** Окно квоты — скользящие сутки, а не календарный день. */
export const REVEAL_WINDOW_MS = 24 * 60 * 60 * 1000;

export interface RevealUsage {
  /** Раскрытий за окно — всего. */
  total: number;
  /** Из них по тому же самому объекту. */
  sameTarget: number;
}

/**
 * Повторное открытие уже раскрытого контакта.
 *
 * Человек вернулся к объявлению, которое смотрел вчера, — это не сбор базы.
 * Такое раскрытие проходит мимо квоты и мимо журнала: ограничиваем число
 * разных контактов, а не число нажатий.
 */
export function isRepeatReveal(usage: RevealUsage): boolean {
  return usage.sameTarget > 0;
}

/** Разрешено ли раскрытие с точки зрения квоты. */
export function isRevealAllowed(usage: RevealUsage, limit = REVEAL_LIMIT_PER_DAY): boolean {
  return isRepeatReveal(usage) || usage.total < limit;
}

/**
 * Писать ли строку в журнал.
 *
 * Пустое раскрытие не дало доступа ни к чему — журнал фиксирует полученный
 * доступ, а не нажатия. Иначе объявления без контактов тратили бы чужую квоту.
 */
export function shouldRecordReveal(usage: RevealUsage, contactsCount: number): boolean {
  return !isRepeatReveal(usage) && contactsCount > 0;
}
