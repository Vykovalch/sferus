import "server-only";

import { del } from "@vercel/blob";
import { logError } from "@/lib/logger";

/**
 * Единственный модуль, который знает про конкретное хранилище файлов.
 *
 * Тот же приём, что с драйвером БД в `lib/db/index.ts` (ARCHITECTURE.md, 9.1):
 * если понадобится переехать с Vercel Blob на S3-совместимое хранилище,
 * правка затрагивает этот файл и эндпоинт загрузки, а всё остальное работает
 * с адресами из БД и о провайдере не знает.
 *
 * Загрузка сюда не входит намеренно: файл идёт из браузера прямо в хранилище,
 * минуя наш сервер, — иначе он упирался бы в лимит тела Server Action, а мы
 * платили бы за перекладывание чужих мегабайт.
 */

/**
 * Удаление файлов — **best-effort**.
 *
 * Сбой хранилища не должен валить операцию, ради которой удаление затевалось:
 * осиротевший файл — это мусор, а неудалённое объявление — баг. Поэтому ошибка
 * логируется и проглатывается, а вызывающий код продолжает работу.
 */
export async function deleteImages(urls: string[]): Promise<void> {
  if (urls.length === 0) return;

  try {
    await del(urls);
  } catch (error) {
    // Адреса файлов в лог не кладутся — только их количество: ссылки Vercel Blob
    // публичные, и складывать их в логи незачем.
    logError("storage", error, { operation: "delete", count: urls.length });
  }
}
