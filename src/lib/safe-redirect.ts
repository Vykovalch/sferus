/**
 * Куда можно вернуть пользователя после входа.
 *
 * Адрес приходит из query-строки, то есть его подставляет тот, кто прислал
 * ссылку. Без проверки `/login?callbackUrl=https://evil.com` уводил бы человека
 * на чужой сайт сразу после успешного входа — причём с настоящей страницы входа
 * Sferus, что и делает приём фишинговым.
 *
 * Принимаем только внутренние пути. Второй символ проверяется отдельно и это
 * не перестраховка: `//evil.com` — протокол-относительный адрес, а `/\evil.com`
 * браузеры трактуют так же; оба начинаются со слэша и оба уводят наружу.
 *
 * Модуль без `server-only`: нужен клиентской форме входа. Отдельным файлом —
 * чтобы правило можно было покрыть тестами: в компоненте оно осталось бы
 * непроверяемым, а «упрощение» этих двух строк возвращает дыру.
 */
export function safeCallbackUrl(value: string | null | undefined, fallback = "/"): string {
  if (!value || !value.startsWith("/")) return fallback;
  if (value[1] === "/" || value[1] === "\\") return fallback;
  return value;
}
