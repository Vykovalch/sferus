import type { MetadataRoute } from "next";
import { absoluteUrl } from "@/lib/site";

/**
 * Правила для поисковых роботов.
 *
 * Без этого файла карту сайта пришлось бы отдавать роботам вручную через
 * панели вебмастера — `robots.txt` со ссылкой на неё и есть штатный способ
 * о ней сообщить.
 *
 * Закрытые разделы перечислены не ради безопасности — вход их и так защищает,
 * а `robots.txt` вообще не средство защиты и читается кем угодно. Смысл в том,
 * чтобы робот не тратил на них обход и не приводил людей из выдачи на страницу
 * входа вместо содержимого.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: [
        // Личный кабинет и админка: за входом, в выдаче им делать нечего.
        "/dashboard",
        "/admin",
        // Служебные эндпоинты.
        "/api/",
        // Результаты внутреннего поиска: адресов бесконечно много,
        // содержимое дублирует каталог. Те же страницы помечены `noindex`
        // в метаданных — здесь дублируем, чтобы робот на них не ходил вовсе.
        "/services?q=",
      ],
    },
    sitemap: absoluteUrl("/sitemap.xml"),
  };
}
